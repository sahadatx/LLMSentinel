"""JSON, SARIF and Markdown finding reports."""

from __future__ import annotations

import json
import os
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from sentinel.scanner.source import Finding


def json_report(findings: Iterable[Finding]) -> str:
    return json.dumps({"tool": {"name": "LLMSentinel", "version": "3.0.0"}, "findings": [item.as_dict() for item in findings]}, indent=2)


def sarif_report(findings: Iterable[Finding]) -> str:
    items = list(findings)
    rules = sorted({item.rule_id for item in items})
    results = []
    for item in items:
        level = "error" if item.severity in {"CRITICAL", "HIGH"} else "warning" if item.severity == "MEDIUM" else "note"
        results.append({
            "ruleId": item.rule_id,
            "level": level,
            "message": {"text": item.message},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": Path(os.path.relpath(Path(item.path).resolve(), Path.cwd())).as_posix()}, "region": {"startLine": item.line}}}],
            "properties": {"severity": item.severity, "cwe": item.cwe, "snippet": item.snippet},
        })
    document: dict[str, Any] = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{"tool": {"driver": {"name": "LLMSentinel", "version": "3.0.0", "rules": [{"id": rule} for rule in rules]}}, "results": results}],
    }
    return json.dumps(document, indent=2)


def markdown_report(findings: Iterable[Finding], title: str = "LLMSentinel Scan Report") -> str:
    items = list(findings)
    lines = [f"# {_markdown_text(title)}", "", f"Findings: **{len(items)}**", "", "| Severity | Rule | Location | Finding |", "|---|---|---|---|"]
    for item in items:
        lines.append("| " + " | ".join((
            _markdown_cell(item.severity),
            _markdown_cell(item.rule_id),
            _markdown_cell(f"{item.path}:{item.line}"),
            _markdown_cell(item.message),
        )) + " |")
    if not items:
        lines.append("| — | — | — | No findings. |")
    lines += ["", "Generated by LLMSentinel 3.0.0. Review findings before treating them as confirmed vulnerabilities."]
    return "\n".join(lines)


def _markdown_text(value: str) -> str:
    return _markdown_escape(value).replace("\r\n", " ").replace("\r", " ").replace("\n", " ")


def _markdown_cell(value: str) -> str:
    return _markdown_escape(value).replace("\r\n", "<br>").replace("\r", "<br>").replace("\n", "<br>").replace("|", "\\|")


def _markdown_escape(value: str) -> str:
    escaped = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for character in ("\\", "`", "*", "_", "[", "]", "!", "#"):
        escaped = escaped.replace(character, "\\" + character)
    return escaped


def write_report(content: str, output: str | Path | None) -> None:
    if output:
        destination = Path(output)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content + "\n", encoding="utf-8")
