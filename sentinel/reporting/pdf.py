"""Compact executive PDF summary for static scan findings."""

from __future__ import annotations

from collections import Counter
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from sentinel.scanner.source import Finding


def pdf_report(findings: list[Finding]) -> bytes:
    buffer = BytesIO()
    document = SimpleDocTemplate(buffer, pagesize=landscape(A4), rightMargin=15 * mm, leftMargin=15 * mm, topMargin=14 * mm, bottomMargin=14 * mm, title="LLMSentinel Executive Scan Report", author="LLMSentinel")
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallCell", parent=styles["BodyText"], fontSize=7.5, leading=9, alignment=TA_LEFT, wordWrap="CJK"))
    styles.add(ParagraphStyle(name="Severity", parent=styles["BodyText"], fontSize=8, leading=10, textColor=colors.HexColor("#0D5443")))
    counts = Counter(item.severity for item in findings)
    story = [Paragraph("LLMSentinel Executive Scan Report", styles["Title"]), Spacer(1, 4 * mm)]
    story.append(Paragraph(f"Total findings: <b>{len(findings)}</b> &nbsp; Critical: <b>{counts['CRITICAL']}</b> &nbsp; High: <b>{counts['HIGH']}</b> &nbsp; Medium: <b>{counts['MEDIUM']}</b> &nbsp; Low / Info: <b>{counts['LOW'] + counts['INFO']}</b>", styles["BodyText"]))
    story.append(Spacer(1, 3 * mm))
    story.append(Paragraph("This report is generated by a starter static analyzer. Findings are leads for human review and are not confirmed vulnerabilities.", styles["BodyText"]))
    story.append(Spacer(1, 6 * mm))
    rows = [["Severity", "Rule", "Location", "Finding"]]
    for item in findings:
        rows.append([
            Paragraph(escape(item.severity), styles["Severity"]),
            Paragraph(escape(item.rule_id), styles["SmallCell"]),
            Paragraph(escape(f"{item.path}:{item.line}"), styles["SmallCell"]),
            Paragraph(escape(item.message), styles["SmallCell"]),
        ])
    if len(rows) == 1:
        rows.append(["—", "—", "—", Paragraph("No findings in the scanned inputs.", styles["SmallCell"])])
    table = Table(rows, colWidths=[25 * mm, 50 * mm, 75 * mm, 115 * mm], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#102A2D")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 8),
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#CBD5D5")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F2F6F5")]),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(table)
    document.build(story)
    return buffer.getvalue()
